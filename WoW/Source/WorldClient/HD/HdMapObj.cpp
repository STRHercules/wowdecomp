    // MapObj vertex shader. Source of truth: the 3.3.5 shaders rewritten from their bytecode (the 7 MapObj*.bls
    // families of Shaders/Vertex/vs_3_0), checked numerically against them for every slot, plus the Forever lighting.
    // (Generated by make_hd_mapobj.py from hd_wmo_vs.hlsl; MSVC takes at most 16 KB per string piece.)
    const char kVertexShader[] =
        R"HLSL(// Waystone HD building (WMO / MapObj) vertex shader (vs_3_0). Replaces the 7 Shaders\Vertex\vs_3_0\MapObj*.bls
// families, permutation P = LIT + 2 * (LIGHTS + 15 * SHADOW)  (CMapObj::SelectWorldShaders; LIGHTS 5..14 repeat 0..4).
//   family                     UNIFIED REFL SPECULAR COMP
//   MapObjDiffuse_T1              0     0      0      0
//   MapObjDiffuse_T1_Refl         0     1      0      0
//   MapObjSpecular_T1             0     0      1      0
//   MapObjUDiffuse_T1             1     0      0      0
//   MapObjUDiffuse_T1_Refl        1     1      0      0
//   MapObjUSpecular_T1            1     0      1      0
//   MapObjUDiffuse_Comp           1     0      0      1
// With c49.z = 0 it computes exactly what the 3.3.5 shader does (COLOR1 = 0 where 3.3.5 writes none).
// With c49.z = 1 (set only for exterior-lit batches, SetLighting 1 or 2) it lights the building like WoW Forever:
// the ambient comes from a sky / horizon / ground hemisphere shaded by a soft wrap of the sun (0.7 .. 1.1), and the
// sun goes out separately in COLOR1.rgb so the pixel shader can cut it fully in shadow instead of darkening
// everything to 70%. The vertex colour (MOCV) keeps the 3.3.5 rule of each path: classic multiplies the light by it,
// unified adds it.
#ifndef UNIFIED
#define UNIFIED 0
#endif
#ifndef REFL
#define REFL 0
#endif
#ifndef SPECULAR
#define SPECULAR 0
#endif
#ifndef COMP
#define COMP 0
#endif
#ifndef LIT
#define LIT 0
#endif
#ifndef LIGHTS
#define LIGHTS 0
#endif
#ifndef SHADOW
#define SHADOW 0
#endif

// texture coordinates after the first one(s) move up by one in the Refl and Comp families
#define SHIFT (REFL || COMP)
// the normal is needed for the light, the reflection and the shadow facing term
#define NEED_NORMAL (LIT || REFL || SHADOW)

float4 cProj[4]       : register(c2);   // rows of the projection (CShaderEffect::UpdateProjMatrix)
float4 cAmbient       : register(c10);  // SetLighting: ambient (mode 1 light1.ambient, 2 mid1, 3 MOHD colour)
float4 cDiffuse       : register(c11);  // SetLighting: sun colour (mode 1 light1.diffuse, 2 mid0, 3 black)
float4 cSunDir        : register(c12);  // view-space sun direction; the light falls along it (shaders use -c12)
float4 cSpecular      : register(c13);  // rgb = specular colour, w = power (14)
float4 cLightColor[4] : register(c17);  // local lights (CShaderEffect::ComputeLocalLights)
float4 cLightPos[4]   : register(c21);  // view space
float4 cLightAtt0     : register(c25);  // constant attenuation of light 0..3 in x..w
float4 cLightAtt1     : register(c26);  // linear
float4 cLightAtt2     : register(c27);  // quadratic
float4 cMatDiffuse    : register(c28);  // unified: material diffuse (0x7F7F7F)
float4 cEmissive      : register(c29);  // (s_emissiveAmbient + SIDN) / 2
float4 cFog           : register(c30);  // x scale, y bias, z power
float4 cWorldView[3]  : register(c31);  // rows of transpose(world * view)
float4 cShadowMtx[12] : register(c224); // dyn rows c224..226, bands c227..232, band 2 coordinates c233..235
float4 cHdLight       : register(c49);  // z = 1 Forever lighting on this batch (exterior-lit only); x, y, w unused here
float4 cHdLight2      : register(c50);  // x = ambient strength in Forever lighting (1 = the ambient as it is)
float4 cHdHorizon     : register(c51);  // rgb = Forever's horizon ambient / its sky ambient, per channel
float4 cHdGround      : register(c52);  // rgb = Forever's ground ambient / its sky ambient, per channel
float4 cHdUp          : register(c53);  // xyz = world up (0, 0, 1) in view space (the hemisphere axis)

#if LIGHTS
// local light i at view position vp, normal n; k = its constant, linear and quadratic attenuation
// (3.3.5: no saturate per light, attenuation 1 / (k0 + k1 d + k2 d^2))
float3 LocalLight(int i, float k0, float k1, float k2, float3 vp, float3 n)
{
    float3 l = cLightPos[i].xyz - vp;
    float d2 = dot(l, l);
    float r = rsqrt(d2);
    float d = d2 * r;
    return cLightColor[i].xyz * (max(dot(l, n) * r, 0.0) * (1.0 / (k0 + k1 * d + k2 * d2)));
}
#endif

void main(
    float4 iPos : POSITION0,
#if NEED_NORMAL
    float3 iNormal : NORMAL0,
#endif
    float4 iColor : COLOR0,
#if COMP
    float4 iColor2 : COLOR1,
#endif
    float2 iTex0 : TEXCOORD0,
#if COMP
    float2 iTex1 : TEXCOORD1,
#endif
    out float4 oPos : POSITION0,
    out float4 oColor : COLOR0,
    out float4 oColor2 : COLOR1,
    out float2 oTex0 : TEXCOORD0,
#if SHIFT
    out float2 oTex1 : TEXCOORD1,
#endif
#if SHADOW
#if SHIFT
    out float3 oViewPos : TEXCOORD2,
    out float3 oNormal : TEXCOORD3,
#if SHADOW == 1
    out float3 oShadow0 : TEXCOORD4,
#else
    out float4 oShadow0 : TEXCOORD4,
    out float4 oShadow1 : TEXCOORD5,
    out float4 oShadow2 : TEXCOORD6,
#endif
#else
    out float3 oViewPos : TEXCOORD1,
    out float3 oNormal : TEXCOORD2,
#if SHADOW == 1
    out float3 oShadow0 : TEXCOORD3,
#else
    out float4 oShadow0 : TEXCOORD3,
    out float4 oShadow1 : TEXCOORD4,
    out float4 oShadow2 : TEXCOORD5,
#endif
#endif
#endif
    out float oFog : FOG)
{
    float4 vp = float4(dot(cWorldView[0], iPos), dot(cWorldView[1], iPos), dot(cWorldView[2], iPos), 1.0);
    oPos = float4(dot(cProj[0], vp), dot(cProj[1], vp), dot(cProj[2], vp), dot(cProj[3], vp));
    oFog = min(pow(max(vp.z * cFog.x + cFog.y, 0.0), cFog.z), 1.0);

#if NEED_NORMAL
    // normal: worldView 3x3, renormalised
    float3 n = normalize(float3(dot(cWorldView[0].xyz, iNormal), dot(cWorldView[1].xyz, iNormal), dot(cWorldView[2].xyz, iNormal)));
#endif

    oColor2 = float4(0.0, 0.0, 0.0, 0.0);
#if COMP
    oColor2 = iColor2;
#endif

#if LIT
    float3 points = float3(0.0, 0.0, 0.0);
#if LIGHTS >= 1
    points = points + LocalLight(0, cLightAtt0.x, cLightAtt1.x, cLightAtt2.x, vp.xyz, n);
#endif
#if LIGHTS >= 2
    points = points + LocalLight(1, cLightAtt0.y, cLightAtt1.y, cLightAtt2.y, vp.xyz, n);
#endif
#if LIGHTS >= 3
    points = points + LocalLight(2, cLightAtt0.z, cLightAtt1.z, cLightAtt2.z, vp.xyz, n);
#endif
#if LIGHTS >= 4
    points = points + LocalLight(3, cLightAtt0.w, cLightAtt1.w, cLightAtt2.w, vp.xyz, n);
#endif
    float nl = dot(-cSunDir.xyz, n);
    [branch] if (cHdLight.z > 0.5) {
        // HD: Forever. Ambient: horizon colour for a wall, sky colour for a roof facing up, ground colour for an
        // overhang; the client's ambient is the sky colour (Forever's when hdForeverLight is 1, so horizon and ground
        // are then Forever's own colours). Then a wrap of the sun over it, and the sun on its own in COLOR1.
        float up = dot(normalize(cHdUp.xyz), n);
        float3 sky = cAmbient.xyz * cHdLight2.x;
        float3 horizon = sky * cHdHorizon.xyz;
        float3 hemi = horizon + (sky - horizon) * saturate(up) + (sky * cHdGround.xyz - horizon) * saturate(-up);
        float3 ambient = hemi * (nl * 0.2 + 0.9) + points;
        float3 direct = cDiffuse.xyz * saturate(nl);
        // like 3.3.5 (saturate of the light), a channel never goes over 1: both parts are scaled down together
        float3 fit = 1.0 / max(ambient + direct, 1.0);
#if UNIFIED
        oColor = float4(saturate(cMatDiffuse.xyz * (ambient * fit) + iColor.xyz + cEmissive.xyz), saturate(iColor.w));
        oColor2.xyz = saturate(cMatDiffuse.xyz * (direct * fit));
#else
        oColor = float4(saturate(iColor.xyz * (ambient * fit) + cEmissive.xyz), saturate(iColor.w));
        oColor2.xyz = saturate(iColor.xyz * (direct * fit));
#endif
    } else {
        float3 light = saturate(cDiffuse.xyz * saturate(nl) + cAmbient.xyz + points);
#if UNIFIED
        oColor = float4(saturate(cMatDiffuse.xyz * light + iColor.xyz + cEmissive.xyz), saturate(iColor.w));
#else
        oColor = float4(saturate(iColor.xyz * light + cEmissive.xyz), saturate(iColor.w));
#endif
#if SPECULAR
        float3 h = normalize(normalize(vp.xyz) + cSunDir.xyz);
        oColor2 = float4(pow(saturate(dot(n, -h)), cSpecular.w) * cSpecular.xyz, 1.0);
#endif
    }
#else
    oColor = iColor;
#endif

    oTex0 = iTex0;
#if REFL
    float3 e = normalize(vp.xyz);
    oTex1 = (e - n * (2.0 * dot(e, n))).xy;
#endif
#if COMP
    oTex1 = iTex1;
#endif

#if SHADOW
    oViewPos = vp.xyz;
    oNormal = n;
#if SHADOW == 1
    oShadow0 = float3(dot(vp, cShadowMtx[0]), dot(vp, cShadowMtx[1]), dot(vp, cShadowMtx[2]));
#else
    oShadow0 = float4(dot(vp, cShadowMtx[0]), dot(vp, cShadowMtx[1]), dot(vp, cShadowMtx[2]), dot(vp, cShadowMtx[9]));
    oShadow1 = float4(dot(vp, cShadowMtx[3]), dot(vp, cShadowMtx[4]), dot(vp, cShadowMtx[5]), dot(vp, cShadowMtx[10]));
    oShadow2 = float4(dot(vp, cShadowMtx[6]), dot(vp, cShadowMtx[7]), dot(vp, cShadowMtx[8]), dot(vp, cShadowMtx[11]));
#endif
#endif
}
)HLSL";

    // MapObj pixel shaders (7 families x 16 permutations), same method.
    const char kPixelShader[] =
        R"HLSL(// Waystone HD building (WMO / MapObj) pixel shader (ps_3_0). Replaces the 7 Shaders\Pixel\ps_3_0\MapObj*.bls
// families, permutation P = SHADOW + 4 * PCF + 8 * ALPHA_TEST  (CShaderEffect::SelectShadowShader).
//   KIND 0 = MapObjDiffuse      (alpha = texture alpha * vertex alpha)
//        1 = MapObjSpecular, MapObjMetal, MapObjOpaque (byte-identical in 3.3.5; alpha = vertex alpha)
//        2 = MapObjEnv          (+ texture alpha * environment texture)
//        3 = MapObjEnvMetal     (+ texture alpha * texture * environment texture)
//        4 = MapObjComposite    (two textures blended by COLOR1.w)
//   SHADOW 0 none, 1 player shadow, 2 player shadow + 3 sun bands, 3 near cascade + 3 sun bands; PCF 1 = hardware
//   depth compare (D24) instead of the R32F manual compare; ALPHA_TEST 1 = discard below c2.w in the shader.
// COLOR1.rgb comes from the HD vertex shader: the sun's light (Forever lighting only).
// With c16.x = 0 it computes exactly what the 3.3.5 shader does: the shadow S darkens the whole light to 70%.
// With c16.x = 1 (exterior-lit batch, Forever lighting) the sun is cut fully by the shadow and the ambient (COLOR0)
// is left alone: light = saturate(COLOR0 + COLOR1 * S). c16.y = 1 is the test view: only the sun after the shadow.
#ifndef KIND
#define KIND 0
#endif
#ifndef SHADOW
#define SHADOW 0
#endif
#ifndef PCF
#define PCF 0
#endif
#ifndef ALPHA_TEST
#define ALPHA_TEST 0
#endif

#define TWO_TEX (KIND >= 2)

float4 cFogColor     : register(c2);   // rgb = fog colour, w = alpha reference (ALPHA_TEST)
float4 cCutoff       : register(c3);   // view-space plane: past it the shadow fades out
float4 cSunDirView   : register(c4);   // view-space sun direction (shadow facing term)
float4 cPcfOffset[8] : register(c5);   // xy = PCF tap offsets in shadow-map UV (c5..c12)
float4 cHdPs         : register(c16);  // HD: x = 1 Forever lighting on this batch, y = 1 test view
// (not c15: the Vulkan backend overwrites pixel c14 and c15 with its fixed-function fog at every draw)

sampler2D sTex0      : register(s0);
#if TWO_TEX
sampler2D sTex1      : register(s1);   // environment (Env, EnvMetal) or second texture (Composite)
#endif
#if SHADOW >= 1
sampler2D sShadow0   : register(s4);   // dynamic (player) shadow, or near cascade in mode 3
#endif
#if SHADOW >= 2
sampler2D sShadow1   : register(s5);   // sun shadow band 0
sampler2D sShadow2   : register(s6);   // band 1
sampler2D sShadow3   : register(s7);   // band 2
#endif

// one shadow tap at shadow-map UV uv for light-space depth z: 1 = lit, 0 = shadowed
float Tap(sampler2D s, float2 uv, float z)
{
#if PCF
    return tex2Dlod(s, float4(uv, z, 0.0)).x;
#else
    return step(z, tex2Dlod(s, float4(uv, 0.0, 0.0)).x);
#endif
}

// centre + offsets 0,2,4,6 ; returns the SUM (0..5)
float Sum5(sampler2D s, float2 c, float z)
{
    float2 uv = c * 0.5 + 0.5;
    float sum = Tap(s, uv, z);
    sum = sum + Tap(s, uv + cPcfOffset[0].xy, z);
    sum = sum + Tap(s, uv + cPcfOffset[2].xy, z);
    sum = sum + Tap(s, uv + cPcfOffset[4].xy, z);
    sum = sum + Tap(s, uv + cPcfOffset[6].xy, z);
    return sum;
}

// centre + all 8 offsets ; returns the SUM (0..9)
float Sum9(sampler2D s, float2 c, float z)
{
    float2 uv = c * 0.5 + 0.5;
    float sum = Tap(s, uv, z);
    sum = sum + Tap(s, uv + cPcfOffset[0].xy, z);
    sum = sum + Tap(s, uv + cPcfOffset[1].xy, z);
    sum = sum + Tap(s, uv + cPcfOffset[2].xy, z);
    sum = sum + Tap(s, uv + cPcfOffset[3].xy, z);
    sum = sum + Tap(s, uv + cPcfOffset[4].xy, z);
    sum = sum + Tap(s, uv + cPcfOffset[5].xy, z);
    sum = sum + Tap(s, uv + cPcfOffset[6].xy, z);
    sum = sum + Tap(s, uv + cPcfOffset[7].xy, z);
    return sum;
}

// edge fades (the float32 constants of the 3.3.5 shaders, written out in full)
float EdgeFade(float2 c)
{
    return saturate(max(abs(c.x), abs(c.y)) * -3.4482758045196533 + 3.4137930870056152);
}
float EdgeFade2(float2 c)
{
    return saturate(max(abs(c.x), abs(c.y)) * -11.11111068725586 + 11.0);
}

void main(
    float4 iColor : COLOR0,
    float4 iColor2 : COLOR1,
    float2 iTex0 : TEXCOORD0,
#if TWO_TEX
    float2 iTex1 : TEXCOORD1,
#endif
#if SHADOW
#if TWO_TEX
    float3 iViewPos : TEXCOORD2,
    float3 iNormal : TEXCOORD3,
#if SHADOW == 1
    float3 iShadow0 : TEXCOORD4,
#else
    float4 iShadow0 : TEXCOORD4,
    float4 iShadow1 : TEXCOORD5,
    float4 iShadow2 : TEXCOORD6,
#endif
#else
    float3 iViewPos : TEXCOORD1,
    float3 iNormal : TEXCOORD2,
#if SHADOW == 1
    float3 iShadow0 : TEXCOORD3,
#else
    float4 iShadow0 : TEXCOORD3,
    float4 iShadow1 : TEXCOORD4,
    float4 iShadow2 : TEXCOORD5,
#endif
#endif
#endif
    float iFog : FOG,
    out float4 oColor : COLOR0)
{
    // ---- textures and alpha
#if KIND == 4
    float4 t = lerp(tex2D(sTex1, iTex1), tex2D(sTex0, iTex0), iColor2.w);
#else
    float4 t = tex2D(sTex0, iTex0);
#endif
#if KIND == 0 || KIND == 4
    float alpha = t.w * iColor.w;
#else
    float alpha = iColor.w;
#endif
#if ALPHA_TEST
    clip(alpha - cFogColor.w);
#endif

    // ---- shadow term S (1 = lit)
    float S = 1.0;
#if SHADOW
    float fade = EdgeFade(iShadow0.xy);
#if SHADOW == 1 || SHADOW == 2
    [branch] if (fade > 0.0099999997764825821) {
        [branch] if (10.0 < iViewPos.z) {
            S = fade * (Sum5(sShadow0, iShadow0.xy, iShadow0.z) * 0.20000000298023224 - 1.0) + 1.0;
        } else {
            S = fade * (Sum9(sShadow0, iShadow0.xy, iShadow0.z) * 0.1111111119389534 - 1.0) + 1.0;
        }
#if SHADOW == 1
        S = min(S, 1.0);
#endif
    }
#else
    [branch] if (fade > 0.0) {
        S = Sum5(sShadow0, iShadow0.xy, iShadow0.z) * 0.20000000298023224;
    }
#endif
    // past the cutoff plane the shadow fades out
    S = lerp(S, 1.0, saturate(dot(iViewPos, cCutoff.xyz) + cCutoff.w));
#if SHADOW >= 2
    float band;
    [branch] if (max(abs(iShadow1.x), abs(iShadow1.y)) < 1.0) {
        band = Sum5(sShadow1, iShadow1.xy, iShadow1.z) * 0.20000000298023224;
    } else {
        [branch] if (max(abs(iShadow2.x), abs(iShadow2.y)) < 1.0) {
            band = Sum5(sShadow2, iShadow2.xy, iShadow2.z) * 0.20000000298023224;
        } else {
            float3 c3 = float3(iShadow0.w, iShadow1.w, iShadow2.w);
            band = EdgeFade2(c3.xy) * (Sum5(sShadow3, c3.xy, c3.z) * 0.20000000298023224 - 1.0) + 1.0;
        }
    }
    S = min(band, S);
#endif
    // surfaces seen edge-on from the sun lose the shadow
    float facing = 1.2000000476837158 - abs(dot(cSunDirView.xyz, iNormal));
    facing = facing * facing;
    S = lerp(S, 1.0, saturate(facing * facing));
    float3 light = iColor.xyz * (S * 0.30000001192092896 + 0.699999988079071);
#else
    float3 light = iColor.xyz;
#endif

    // HD: Forever (exterior-lit batch): the shadow takes only the sun, the ambient stays whole
    [branch] if (cHdPs.x > 0.5) {
        light = saturate(iColor.xyz + iColor2.xyz * S);
    }

    // ---- combine (3.3.5: 2 x texture x light, + the environment term, then the fog)
    float3 col = t.xyz * light;
    col = col + col;
#if KIND == 2
    col = col + t.w * tex2D(sTex1, iTex1).xyz;
#endif
#if KIND == 3
    col = col + (t.w * t.xyz) * tex2D(sTex1, iTex1).xyz;
#endif
    oColor = float4((col - cFogColor.xyz) * iFog + cFogColor.xyz, alpha);
    // HD: test view (hdWmoLight 3): only the sun after the shadow, no texture, no ambient, no fog
    if (cHdPs.y > 0.5) oColor.xyz = iColor2.xyz * S * 2.0;
}
)HLSL";


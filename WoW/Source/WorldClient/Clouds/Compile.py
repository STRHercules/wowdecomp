"""Compile the cloud shaders to committed SPIR-V; pass a glslang path or put it on PATH."""
import importlib.util
from pathlib import Path

HERE = Path(__file__).resolve().parent
helper = HERE.parents[3] / "Engine/Source/Lumenveil/Shaders/Compile.py"
spec = importlib.util.spec_from_file_location("shader_compile", helper)
compiler = importlib.util.module_from_spec(spec)
spec.loader.exec_module(compiler)


def main():
    glslang = compiler.find_glslang()
    lines = ["// Generated by Clouds/Compile.py; edit the HLSL sources instead.", ""]
    for source, symbol, stage in [
        ("sky_panorama_cs.hlsl", "kCloudPanorama", "comp"),
        ("sky_multiscatter_ps.hlsl", "kCloudScatter", "frag"),
        ("sky_clouds_ps.hlsl", "kCloudDraw", "frag"),
    ]:
        words = compiler.compile_to_words(glslang, [
            "-D", "-V", "-Os", "-S", stage, "-e", "main", "--target-env", "vulkan1.0",
            "--hlsl-dx9-compatible", "--hlsl-iomap", "-I" + str(HERE),
        ], str(HERE / source))
        lines.append(f"static const uint32_t {symbol}[] = {{")
        for i in range(0, len(words), 8):
            lines.append("    " + ", ".join(f"0x{w:08X}" for w in words[i:i + 8]) + ",")
        lines.extend(["};", ""])
    (HERE / "Spirv.inc").write_text("\n".join(lines))


if __name__ == "__main__":
    main()

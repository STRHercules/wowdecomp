std::string Lower(const char* s) {
    std::string out(s ? s : "");
    for (char& c : out) c = static_cast<char>(std::tolower(static_cast<unsigned char>(c)));
    return out;
}

// ---- Atlas table -------------------------------------------------------------------------------------------------

std::unordered_map<std::string, RetailAtlasInfo>* s_atlases;
std::unordered_map<CSimpleTexture*, std::string> s_textureAtlas; // cleared in ~CSimpleTexture

void LoadAtlases() {
    if (!s_atlases) s_atlases = new std::unordered_map<std::string, RetailAtlasInfo>();
    void* data = nullptr;
    uint32_t bytes = 0;

    // Generated by Tools/RetailUI/make_atlas_table.py; one "name;fdid;w;h;l;r;t;b;flags" line per element. Packed
    // clients carry it in an MPQ; a development install has it loose in the addon that uses it. ReadFile, as the addon
    // loader uses, also finds loose files; LoadFile reads archives only.
    if (!SFile::ReadFile(nullptr, "Interface\\Esteria\\RetailAtlas.txt", &data, &bytes, 0, 1, nullptr)
        && !SFile::ReadFile(nullptr, "Interface\\AddOns\\EsteriaRetailUI\\RetailAtlas.txt", &data, &bytes, 0, 1, nullptr)) {
        return;
    }

    std::string text(static_cast<const char*>(data), bytes);
    SFile::Unload(data);
    s_atlases->reserve(16384);

    size_t at = 0;
    while (at < text.size()) {
        size_t end = text.find('\n', at);
        if (end == std::string::npos) end = text.size();
        std::string line = text.substr(at, end - at);
        at = end + 1;

        if (line.empty() || line[0] == '#') continue;
        if (line.back() == '\r') line.pop_back();

        size_t semi = line.find(';');
        if (semi == std::string::npos) continue;

        RetailAtlasInfo info = {};
        if (std::sscanf(line.c_str() + semi + 1, "%u;%f;%f;%f;%f;%f;%f;%u", &info.fileDataId, &info.width, &info.height,
                &info.left, &info.right, &info.top, &info.bottom, &info.flags) >= 7) {
            line.resize(semi);
            (*s_atlases)[Lower(line.c_str())] = info;
        }
    }
}

// ---- Lua helpers -------------------------------------------------------------------------------------------------

void PushObject(lua_State* L, FrameScript_Object* object) {
    if (!object->m_luaRegistered) {
        object->RegisterScriptObject(nullptr);
    }

    lua_rawgeti(L, LUA_REGISTRYINDEX, object->m_luaObjectRef);
}

// The object behind a widget table (its [0] field), or null for any other value.
FrameScript_Object* ToObject(lua_State* L, int32_t index) {
    if (lua_type(L, index) != LUA_TTABLE) return nullptr;
    lua_rawgeti(L, index, 0);
    auto* object = static_cast<FrameScript_Object*>(lua_touserdata(L, -1));
    lua_pop(L, 1);
    return object;
}

int32_t s_methodFactory = LUA_NOREF;
int32_t s_chainFactory = LUA_NOREF;

int32_t Factory(lua_State* L, int32_t& ref, const char* source, const char* name) {
    if (ref == LUA_NOREF) {
        if (luaL_loadbuffer(L, source, std::strlen(source), name)) {
            lua_pop(L, 1);
            return 0;
        }
        ref = luaL_ref(L, LUA_REGISTRYINDEX);
    }

    lua_rawgeti(L, LUA_REGISTRYINDEX, ref);
    return 1;
}

struct PendingAnchor {
    CScriptRegion* region;
    FRAMEPOINT point;
    FRAMEPOINT relativePoint;
    std::string key;
    float x;
    float y;
};

std::vector<PendingAnchor> s_pendingAnchors;

// "$parent.$parent.Name.Child": $parent walks to the owning frame, other parts read keys off the widget tables.
CLayoutFrame* ResolveKey(CScriptRegion* region, const std::string& key) {
    lua_State* L = FrameScript_GetContext();
    FrameScript_Object* current = region;
    size_t at = 0;

    while (current && at <= key.size()) {
        size_t dot = key.find('.', at);
        std::string part = key.substr(at, dot == std::string::npos ? std::string::npos : dot - at);
        at = dot == std::string::npos ? key.size() + 1 : dot + 1;

        if (part.empty()) continue;

        if (part == "$parent") {
            current = static_cast<CScriptObject*>(current)->GetScriptObjectParent();
            continue;
        }

        PushObject(L, current);
        lua_getfield(L, -1, part.c_str());
        current = ToObject(L, -1);
        lua_pop(L, 2);
    }

    if (!current || current == region || !current->IsA(CScriptRegion::GetObjectType())) {
        return nullptr;
    }

    return static_cast<CScriptRegion*>(static_cast<CScriptObject*>(current));
}


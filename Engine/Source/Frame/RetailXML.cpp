// Handlers an intrinsic declared with intrinsicOrder: 1 runs before, 2 after, whatever a frame later sets for the
// same script. Kept in a weak-keyed Lua table by function (registry numbers are reused once freed); the combined
// handler is sticky too, so further overrides keep it.
static int32_t s_stickyTable = LUA_NOREF;

static int32_t StickyOrder(lua_State* L, int32_t ref) {
    if (ref <= 0 || s_stickyTable == LUA_NOREF) return 0;
    lua_rawgeti(L, LUA_REGISTRYINDEX, s_stickyTable);
    lua_rawgeti(L, LUA_REGISTRYINDEX, ref);
    lua_rawget(L, -2);
    int32_t order = static_cast<int32_t>(lua_tonumber(L, -1));
    lua_pop(L, 2);
    return order;
}

static void SetSticky(lua_State* L, int32_t ref, int32_t order) {
    if (s_stickyTable == LUA_NOREF) {
        lua_newtable(L);
        lua_newtable(L);
        lua_pushstring(L, "k");
        lua_setfield(L, -2, "__mode");
        lua_setmetatable(L, -2);
        s_stickyTable = luaL_ref(L, LUA_REGISTRYINDEX);
    }
    lua_rawgeti(L, LUA_REGISTRYINDEX, s_stickyTable);
    lua_rawgeti(L, LUA_REGISTRYINDEX, ref);
    lua_pushnumber(L, order);
    lua_rawset(L, -3);
    lua_pop(L, 1);
}

static int32_t Chain(lua_State* L, int32_t first, int32_t second) {
    if (!Factory(L, s_chainFactory, "local a, b = ... return function(...) a(...) return b(...) end", "=inherit")) {
        return 0;
    }
    lua_rawgeti(L, LUA_REGISTRYINDEX, first);
    lua_rawgeti(L, LUA_REGISTRYINDEX, second);
    if (lua_pcall(L, 2, 1, 0) != 0) {
        lua_pop(L, 1);
        return 0;
    }
    return luaL_ref(L, LUA_REGISTRYINDEX);
}

static int32_t ScriptRefInner(lua_State* L, XMLNode* child, int32_t inheritedRef, int32_t ownRef);

// The handler a script element ends up with. ownRef is what the element itself defines (function=, a body, or 0);
// method="Name" calls self:Name(...). inherit="prepend" runs the inherited handler first, "append" runs it last,
// anything else replaces it; an intrinsic's intrinsicOrder handler is always kept. Consumes both references; returns
// the reference to store (0 for none).
int32_t RetailXML_ScriptRef(lua_State* L, XMLNode* child, int32_t inheritedRef, int32_t ownRef) {
    const int32_t stickyOrder = StickyOrder(L, inheritedRef);

    if (!stickyOrder) {
        int32_t ref = ScriptRefInner(L, child, inheritedRef, ownRef);
        const char* order = child->GetAttributeByName("intrinsicOrder");
        if (ref > 0 && order && *order) {
            SetSticky(L, ref, !SStrCmpI(order, "postcall", STORM_MAX_STR) ? 2 : 1);
        }
        return ref;
    }

    int32_t own = ScriptRefInner(L, child, 0, ownRef);
    if (own <= 0) {
        return inheritedRef; // nothing new; the intrinsic handler stays
    }

    int32_t ref = stickyOrder == 1 ? Chain(L, inheritedRef, own) : Chain(L, own, inheritedRef);
    luaL_unref(L, LUA_REGISTRYINDEX, inheritedRef); // the chain holds both functions
    luaL_unref(L, LUA_REGISTRYINDEX, own);
    if (ref > 0) {
        SetSticky(L, ref, stickyOrder);
    }
    return ref;
}

static int32_t ScriptRefInner(lua_State* L, XMLNode* child, int32_t inheritedRef, int32_t ownRef) {
    const char* method = child->GetAttributeByName("method");

    if (method && *method && Factory(L, s_methodFactory,
            "local name = ... return function(self, ...) local f = self[name] "
            "if not f then error(\"method \" .. name .. \" is missing on \" .. tostring(self.GetName and self:GetName() or self), 2) end "
            "return f(self, ...) end", "=method")) {
        lua_pushstring(L, method);
        if (lua_pcall(L, 1, 1, 0) == 0) {
            if (ownRef > 0) luaL_unref(L, LUA_REGISTRYINDEX, ownRef);
            ownRef = luaL_ref(L, LUA_REGISTRYINDEX);
        } else {
            lua_pop(L, 1);
        }
    }

    const char* inherit = child->GetAttributeByName("inherit");
    const bool prepend = inherit && !SStrCmpI(inherit, "prepend", STORM_MAX_STR);
    const bool append = inherit && !SStrCmpI(inherit, "append", STORM_MAX_STR);

    if (inheritedRef > 0 && ownRef > 0 && (prepend || append) && Factory(L, s_chainFactory,
            "local a, b = ... return function(...) a(...) return b(...) end", "=inherit")) {
        lua_rawgeti(L, LUA_REGISTRYINDEX, prepend ? inheritedRef : ownRef);
        lua_rawgeti(L, LUA_REGISTRYINDEX, prepend ? ownRef : inheritedRef);
        luaL_unref(L, LUA_REGISTRYINDEX, inheritedRef);
        luaL_unref(L, LUA_REGISTRYINDEX, ownRef);
        if (lua_pcall(L, 2, 1, 0) == 0) {
            return luaL_ref(L, LUA_REGISTRYINDEX);
        }
        lua_pop(L, 1);
        return 0;
    }

    if (ownRef <= 0 && (prepend || append)) {
        return inheritedRef; // the element only marks how to combine; nothing of its own
    }

    if (inheritedRef > 0) {
        luaL_unref(L, LUA_REGISTRYINDEX, inheritedRef);
    }

    return ownRef > 0 ? ownRef : 0;
}

// ---- Script API --------------------------------------------------------------------------------------------------

int32_t RetailXML_Script_SetAtlas(lua_State* L) {
    auto* texture = static_cast<CSimpleTexture*>(FrameScript_GetObjectThis(L, CSimpleTexture::GetObjectType()));
    const char* name = lua_tolstring(L, 2, nullptr);

    if (!name || !*name) {
        RetailXML_ForgetTexture(texture);
        texture->SetTexture(static_cast<const char*>(nullptr), 0, 0, CSimpleTexture::s_textureFilterMode, ImageMode_Normal);
        return 0;
    }

    // SetAtlas(name[, useAtlasSize, filterMode, resetTexCoords])
    lua_pushboolean(L, RetailXML_SetAtlas(texture, name, lua_toboolean(L, 3) != 0, lua_toboolean(L, 5) != 0));
    return 1;
}

int32_t RetailXML_Script_GetAtlas(lua_State* L) {
    auto* texture = static_cast<CSimpleTexture*>(FrameScript_GetObjectThis(L, CSimpleTexture::GetObjectType()));
    const char* name = RetailXML_GetAtlas(texture);

    if (name) {
        lua_pushstring(L, name);
    } else {
        lua_pushnil(L);
    }

    return 1;
}

// GetAtlasInfo(name): the table retail's C_Texture.GetAtlasInfo returns, or nil.
static int32_t Script_GetAtlasInfo(lua_State* L) {
    const RetailAtlasInfo* info = RetailAtlas_Find(lua_tolstring(L, 1, nullptr));

    if (!info) {
        lua_pushnil(L);
        return 1;
    }

    char path[64];
    std::snprintf(path, sizeof(path), "retail/%u.blp", info->fileDataId);

    lua_createtable(L, 0, 10);
    lua_pushnumber(L, info->width);      lua_setfield(L, -2, "width");
    lua_pushnumber(L, info->height);     lua_setfield(L, -2, "height");
    lua_pushnumber(L, info->left);       lua_setfield(L, -2, "leftTexCoord");
    lua_pushnumber(L, info->right);      lua_setfield(L, -2, "rightTexCoord");
    lua_pushnumber(L, info->top);        lua_setfield(L, -2, "topTexCoord");
    lua_pushnumber(L, info->bottom);     lua_setfield(L, -2, "bottomTexCoord");
    lua_pushboolean(L, RetailAtlas_TilesH(info)); lua_setfield(L, -2, "tilesHorizontally");
    lua_pushboolean(L, RetailAtlas_TilesV(info)); lua_setfield(L, -2, "tilesVertically");
    lua_pushnumber(L, info->fileDataId); lua_setfield(L, -2, "file");
    lua_pushstring(L, path);             lua_setfield(L, -2, "filename");
    return 1;
}

static std::unordered_map<std::string, std::string> s_intrinsics;

void RetailXML_RegisterIntrinsic(const char* name, const char* baseTag) {
    if (name && *name && baseTag && *baseTag && Lower(name) != Lower(baseTag)) {
        s_intrinsics[Lower(name)] = baseTag;
    }
}

const char* RetailXML_IntrinsicBase(const char* name) {
    auto it = s_intrinsics.find(Lower(name));
    return it == s_intrinsics.end() ? nullptr : it->second.c_str();
}

// The template's own <Size>, else the first one found along its inherits (depth first, in order).
static bool TemplateSize(const char* name, float& width, float& height, int32_t depth) {
    const char* taint;
    bool locked;
    XMLNode* node = depth < 16 ? FrameXML_AcquireHashNode(name, taint, locked) : nullptr;
    if (!node) return false;
    if (locked) return false;

    bool found = false;
    if (XMLNode* size = node->GetChildByName("Size")) {
        CStatus ignored;
        found = LoadXML_Dimensions(size, width, height, &ignored) != 0;
    }

    const char* inherits = node->GetAttributeByName("inherits");
    char parent[256];
    while (!found && inherits && *inherits) {
        SStrTokenize(&inherits, parent, sizeof(parent), " ,", nullptr);
        if (!parent[0]) break;
        found = TemplateSize(parent, width, height, depth + 1);
    }

    FrameXML_ReleaseHashNode(name);
    return found;
}

// GetTemplateInfo(name): retail C_XMLUtil.GetTemplateInfo's { type, width, height, inherits }, or nil.
static int32_t Script_GetTemplateInfo(lua_State* L) {
    const char* name = lua_tolstring(L, 1, nullptr);
    const char* taint;
    bool locked;
    XMLNode* node = name ? FrameXML_AcquireHashNode(name, taint, locked) : nullptr;

    if (!node) {
        lua_pushnil(L);
        return 1;
    }

    std::string type = node->m_name.m_str;
    const char* inherits = node->GetAttributeByName("inherits");
    std::string inheritList = inherits ? inherits : "";
    if (!locked) FrameXML_ReleaseHashNode(name);

    float width = 0.0f;
    float height = 0.0f;
    TemplateSize(name, width, height, 0);

    lua_createtable(L, 0, 4);
    lua_pushstring(L, type.c_str()); lua_setfield(L, -2, "type");
    // <Size> was read into layout units; retail reports UI pixels.
    const float unit = CoordinateGetAspectCompensation() * 1024.0f;
    lua_pushnumber(L, DDCToNDCWidth(width) * unit);   lua_setfield(L, -2, "width");
    lua_pushnumber(L, DDCToNDCWidth(height) * unit);  lua_setfield(L, -2, "height");
    lua_pushstring(L, inheritList.c_str()); lua_setfield(L, -2, "inherits");
    return 1;
}

// Called as each Lua state (glue, game, every ReloadUI) gets its frame API: registry references from the previous
// state are meaningless in the new one.
void RetailXML_RegisterScriptFunctions() {
    s_methodFactory = LUA_NOREF;
    s_chainFactory = LUA_NOREF;
    s_stickyTable = LUA_NOREF;
    s_pendingAnchors.clear();

    FrameScript_RegisterFunction("GetAtlasInfo", &Script_GetAtlasInfo);
    FrameScript_RegisterFunction("RetailGetAtlasInfo", &Script_GetAtlasInfo); // addons may replace GetAtlasInfo
    FrameScript_RegisterFunction("GetTemplateInfo", &Script_GetTemplateInfo);
}

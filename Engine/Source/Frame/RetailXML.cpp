void RetailXML_LoadObject(FrameScript_Object* object, FrameScript_Object* parent, XMLNode* node, CStatus* status) {
    const char* mixin = node->GetAttributeByName("mixin");
    const char* secureMixin = node->GetAttributeByName("secureMixin");
    const char* parentArray = node->GetAttributeByName("parentArray");
    XMLNode* keyValues = node->GetChildByName("KeyValues");

    if (!(mixin && *mixin) && !(secureMixin && *secureMixin) && !(parentArray && *parentArray) && !keyValues) {
        return;
    }

    lua_State* L = FrameScript_GetContext();
    PushObject(L, object);
    const int32_t self = lua_gettop(L);

    // mixin="A, B": copy each global mixin table's fields onto the widget, as retail's Mixin() does.
    for (const char* list : { mixin, secureMixin }) {
        if (!list || !*list) continue;

        char name[256];
        do {
            SStrTokenize(&list, name, sizeof(name), " ,", nullptr);
            if (!name[0]) break;

            lua_getfield(L, LUA_GLOBALSINDEX, name);
            if (lua_type(L, -1) != LUA_TTABLE) {
                status->Add(STATUS_WARNING, "%s: Unknown mixin %s", object->GetDisplayName(), name);
                lua_pop(L, 1);
                continue;
            }

            lua_pushnil(L);
            while (lua_next(L, -2)) {
                lua_pushvalue(L, -2);
                lua_insert(L, -2);
                lua_settable(L, self);
            }
            lua_pop(L, 1);
        } while (name[0]);
    }

    // <KeyValues><KeyValue key="x" value="1" type="number"/></KeyValues>
    if (keyValues) {
        for (XMLNode* kv = keyValues->m_child; kv; kv = kv->m_next) {
            const char* key = kv->GetAttributeByName("key");
            const char* value = kv->GetAttributeByName("value");
            const char* type = kv->GetAttributeByName("type");
            const char* keyType = kv->GetAttributeByName("keyType");
            if (!key || !*key) continue;

            if (keyType && !SStrCmpI(keyType, "number", STORM_MAX_STR)) {
                lua_pushnumber(L, SStrToFloat(key));
            } else {
                lua_pushstring(L, key);
            }

            if (!type || !*type || !SStrCmpI(type, "string", STORM_MAX_STR)) {
                lua_pushstring(L, value ? value : "");
            } else if (!SStrCmpI(type, "number", STORM_MAX_STR)) {
                lua_pushnumber(L, value ? SStrToFloat(value) : 0.0f);
            } else if (!SStrCmpI(type, "boolean", STORM_MAX_STR)) {
                lua_pushboolean(L, value && !SStrCmpI(value, "true", STORM_MAX_STR));
            } else if (!SStrCmpI(type, "global", STORM_MAX_STR)) {
                // global="Name.Field" is allowed: walk dotted names from _G.
                lua_pushvalue(L, LUA_GLOBALSINDEX);
                std::string path(value ? value : "");
                size_t at = 0;
                while (at <= path.size() && !lua_isnil(L, -1)) {
                    size_t dot = path.find('.', at);
                    std::string part = path.substr(at, dot == std::string::npos ? std::string::npos : dot - at);
                    at = dot == std::string::npos ? path.size() + 1 : dot + 1;
                    if (lua_type(L, -1) != LUA_TTABLE) { lua_pop(L, 1); lua_pushnil(L); break; }
                    lua_getfield(L, -1, part.c_str());
                    lua_remove(L, -2);
                }
            } else {
                lua_pushnil(L);
            }

            lua_settable(L, self);
        }
    }

    // parentArray="Tabs": append the widget to parent.Tabs.
    if (parentArray && *parentArray && parent) {
        PushObject(L, parent);
        lua_getfield(L, -1, parentArray);
        if (lua_type(L, -1) != LUA_TTABLE) {
            lua_pop(L, 1);
            lua_newtable(L);
            lua_pushvalue(L, -1);
            lua_setfield(L, -3, parentArray);
        }
        lua_pushvalue(L, self);
        lua_rawseti(L, -2, static_cast<int32_t>(lua_objlen(L, -2)) + 1);
        lua_pop(L, 2);
    }

    lua_settop(L, self - 1);
}

// ---- Anchors -----------------------------------------------------------------------------------------------------

void RetailXML_LoadRelativeAnchors(CScriptRegion* region, XMLNode* node, CStatus* status) {
    XMLNode* anchors = node->GetChildByName("Anchors");
    if (!anchors) return;

    for (XMLNode* anchor = anchors->m_child; anchor; anchor = anchor->m_next) {
        const char* key = anchor->GetAttributeByName("relativeKey");
        if (!key || !*key) continue;

        PendingAnchor pending = { region, FRAMEPOINT(), FRAMEPOINT(), key, 0.0f, 0.0f };
        const char* pointAttr = anchor->GetAttributeByName("point");
        if (!pointAttr || !StringToFramePoint(pointAttr, pending.point)) continue;

        const char* relativePointAttr = anchor->GetAttributeByName("relativePoint");
        if (!relativePointAttr || !*relativePointAttr || !StringToFramePoint(relativePointAttr, pending.relativePoint)) {
            pending.relativePoint = pending.point;
        }

        XMLNode* offset = anchor->GetChildByName("Offset");
        LoadXML_Dimensions(offset ? offset : anchor, pending.x, pending.y, status);

        if (CLayoutFrame* relative = ResolveKey(region, pending.key)) {
            region->SetPoint(pending.point, relative, pending.relativePoint, pending.x, pending.y, 1);
        } else {
            // Retail lets an anchor name a sibling that is declared further down; retried as frames finish loading.
            s_pendingAnchors.push_back(pending);
        }
    }
}

void RetailXML_ResolvePendingAnchors(bool final, CStatus* status) {
    for (size_t i = 0; i < s_pendingAnchors.size();) {
        PendingAnchor& pending = s_pendingAnchors[i];

        if (CLayoutFrame* relative = ResolveKey(pending.region, pending.key)) {
            pending.region->SetPoint(pending.point, relative, pending.relativePoint, pending.x, pending.y, 1);
        } else if (!final) {
            ++i;
            continue;
        } else {
            status->Add(STATUS_WARNING, "%s: Couldn't find relative key %s", pending.region->GetDisplayName(), pending.key.c_str());
        }

        s_pendingAnchors.erase(s_pendingAnchors.begin() + static_cast<std::ptrdiff_t>(i));
    }
}


// ---- Atlases -----------------------------------------------------------------------------------------------------

const RetailAtlasInfo* RetailAtlas_Find(const char* name) {
    if (!name || !*name) return nullptr;
    static int32_t s_attempts = 0;
    if ((!s_atlases || s_atlases->empty()) && s_attempts < 3) { // a client without the table stops looking
        ++s_attempts;
        LoadAtlases();
    }
    if (!s_atlases) return nullptr;

    auto it = s_atlases->find(Lower(name));
    return it == s_atlases->end() ? nullptr : &it->second;
}

// Retail flags: 4 tiles horizontally ("_" atlases), 2 vertically ("!" atlases). This client tiles by repeating the
// whole texture, so only an atlas spanning the full texture on that axis tiles; a narrower strip (a 1 px tab centre)
// is stretched, which looks the same.
bool RetailAtlas_TilesH(const RetailAtlasInfo* info) {
    return (info->flags & 4) && info->left <= 0.001f && info->right >= 0.999f;
}

bool RetailAtlas_TilesV(const RetailAtlasInfo* info) {
    return (info->flags & 2) && info->top <= 0.001f && info->bottom >= 0.999f;
}

bool RetailXML_SetAtlas(CSimpleTexture* texture, const char* name, bool useAtlasSize, bool resetTexCoords) {
    const RetailAtlasInfo* info = RetailAtlas_Find(name);

    if (!info) {
        return false;
    }

    char path[64];
    std::snprintf(path, sizeof(path), "retail/%u.blp", info->fileDataId);

    const int32_t tileH = RetailAtlas_TilesH(info);
    const int32_t tileV = RetailAtlas_TilesV(info);

    // Retail keeps a flip set before SetAtlas (NineSlice mirrors one corner into four with SetTexCoord(1, 0, 0, 1)):
    // unit-square coordinates are mapped into the atlas region; anything else gets the plain region.
    C2Vector unit[4];
    bool flipped = !resetTexCoords;
    for (uint32_t i = 0; i < 4 && flipped; ++i) {
        unit[i] = texture->m_texCoords[i];
        flipped = (unit[i].x == 0.0f || unit[i].x == 1.0f) && (unit[i].y == 0.0f || unit[i].y == 1.0f);
    }

    if (!texture->SetTexture(path, tileH, tileV, CSimpleTexture::s_textureFilterMode, ImageMode_Normal)) {
        return false;
    }

    C2Vector coords[4];
    coords[0].x = info->left;  coords[0].y = info->top;
    coords[1].x = info->left;  coords[1].y = info->bottom;
    coords[2].x = info->right; coords[2].y = info->top;
    coords[3].x = info->right; coords[3].y = info->bottom;

    if (flipped) {
        for (uint32_t i = 0; i < 4; ++i) {
            coords[i].x = info->left + unit[i].x * (info->right - info->left);
            coords[i].y = info->top + unit[i].y * (info->bottom - info->top);
        }
    }

    texture->SetTexCoord(coords);

    if (useAtlasSize) {
        // Atlas sizes are UI pixels; layout sizes are in the engine's units (as LoadXML_Dimensions converts <Size>).
        const float unit = CoordinateGetAspectCompensation() * 1024.0f;
        texture->SetWidth(NDCToDDCWidth(info->width / unit));
        texture->SetHeight(NDCToDDCWidth(info->height / unit));
    }

    s_textureAtlas[texture] = name;
    return true;
}

const char* RetailXML_GetAtlas(CSimpleTexture* texture) {
    auto it = s_textureAtlas.find(texture);
    return it == s_textureAtlas.end() ? nullptr : it->second.c_str();
}

void RetailXML_ForgetTexture(CSimpleTexture* texture) {
    s_textureAtlas.erase(texture);
}

// Retail names textures by FileDataID ("136235"); those load through the Retail source as retail/<id>.blp.
const char* RetailXML_TexturePath(const char* file, char* buffer, size_t bufferSize) {
    if (!file || !*file) return file;

    for (const char* c = file; *c; ++c) {
        if (!std::isdigit(static_cast<unsigned char>(*c))) return file;
    }

    std::snprintf(buffer, bufferSize, "retail/%s.blp", file);
    return buffer;
}

// ---- Retail texture paths ----------------------------------------------------------------------------------------

static std::unordered_map<std::string, uint32_t>* s_retailTextures;

static std::string TextureKey(const char* file) {
    std::string key = Lower(file);
    for (char& c : key) if (c == '\\') c = '/';
    if (key.size() > 4 && (key.compare(key.size() - 4, 4, ".blp") == 0 || key.compare(key.size() - 4, 4, ".tga") == 0)) {
        key.resize(key.size() - 4);
    }
    return key;
}

const char* RetailXML_TextureFallback(const char* file, char* buffer, size_t bufferSize) {
    if (!file || !*file || (file[0] != 'I' && file[0] != 'i')) return file; // only Interface\ paths are mapped

    if (!s_retailTextures) {
        s_retailTextures = new std::unordered_map<std::string, uint32_t>();
        void* data = nullptr;
        uint32_t bytes = 0;
        // Generated by Tools/RetailUI/make_texture_map.py: "path;fdid" lines.
        if (SFile::ReadFile(nullptr, "Interface\\Esteria\\RetailTextures.txt", &data, &bytes, 0, 1, nullptr)
            || SFile::ReadFile(nullptr, "Interface\\AddOns\\EsteriaRetailUI\\RetailTextures.txt", &data, &bytes, 0, 1, nullptr)) {
            std::string text(static_cast<const char*>(data), bytes);
            SFile::Unload(data);
            size_t at = 0;
            while (at < text.size()) {
                size_t end = text.find('\n', at);
                if (end == std::string::npos) end = text.size();
                std::string line = text.substr(at, end - at);
                at = end + 1;
                size_t semi = line.find(';');
                if (line.empty() || line[0] == '#' || semi == std::string::npos) continue;
                (*s_retailTextures)[line.substr(0, semi)] = static_cast<uint32_t>(std::strtoul(line.c_str() + semi + 1, nullptr, 10));
            }
        }
    }

    auto it = s_retailTextures->find(TextureKey(file));
    if (it == s_retailTextures->end()) return file;

    // The client's own file wins; only a path it lacks comes from the Retail source.
    std::string withExt = std::string(file) + ".blp";
    if (SFile::FileExists(file) || SFile::FileExists(withExt.c_str())) return file;

    std::snprintf(buffer, bufferSize, "retail/%u.blp", it->second);
    return buffer;
}


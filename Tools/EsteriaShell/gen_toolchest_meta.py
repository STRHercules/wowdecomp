"""Generates Addons/EsteriaToolChest/Meta.lua from the server's headers, so the Tool Chest's flag names, enum names and
gameobject Data labels can't drift from the code that reads them.

    python gen_toolchest_meta.py <EsteriaWoW checkout>
"""
import pathlib
import re
import sys

REPO = pathlib.Path(__file__).resolve().parents[2]
game = pathlib.Path(sys.argv[1]) / "src" / "server"

source = "\n".join(p.read_text(encoding="utf-8", errors="replace") for folder in ("game", "shared")
                   for p in (game / folder).rglob("*.h"))

# field -> (constant prefix, "flags" or "enum")
FIELDS = {
    "npcflag": ("UNIT_NPC_FLAG_", "flags"),
    "unit_flags": ("UNIT_FLAG_", "flags"),
    "unit_flags2": ("UNIT_FLAG2_", "flags"),
    "dynamicflags": ("UNIT_DYNFLAG_", "flags"),
    "type_flags": ("CREATURE_TYPE_FLAG_", "flags"),
    "flags_extra": ("CREATURE_FLAG_EXTRA_", "flags"),
    "gameobject_template_addon.flags": ("GO_FLAG_", "flags"),
    "rank": ("CREATURE_ELITE_", "enum"),
    "family": ("CREATURE_FAMILY_", "enum"),
    "creature_template.type": ("CREATURE_TYPE_", "enum"),
    "gameobject_template.type": ("GAMEOBJECT_TYPE_", "enum"),
    "MovementType": ("", "movement"),
}


def values(prefix, kind):
    found = {}
    pattern = rf"^\s*{prefix}([A-Z0-9_]+)\s*=\s*(0x[0-9A-Fa-f]+|\d+)\s*,?"
    for match in re.finditer(pattern, source, re.M):
        name, value = match.group(1), int(match.group(2), 0)
        if kind == "flags" and (value == 0 or value & (value - 1)):
            continue  # a composite or "none": only single bits get a checkbox
        if prefix == "CREATURE_TYPE_" and name.startswith("FLAG_"):
            continue
        found.setdefault(value, name.replace("_", " ").title())
    return dict(sorted(found.items()))


def lua(text):
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


lines = ["-- Generated by Tools/EsteriaShell/gen_toolchest_meta.py from the server's headers. Do not edit.", "EsteriaToolChestMeta = {", "    fields = {"]
for field, (prefix, kind) in FIELDS.items():
    if kind == "movement":
        rows, kind = {0: "Idle", 1: "Random", 2: "Waypoint"}, "enum"
    else:
        rows = values(prefix, kind)
    if not rows:
        raise SystemExit(f"nothing found for {field} ({prefix})")
    body = ", ".join(f"{{ {v}, {lua(n)} }}" for v, n in rows.items())
    lines.append(f"        [{lua(field)}] = {{ kind = {lua(kind)}, {body} }},")
lines += ["    },", "    data = {"]

# The union in GameObjectTemplate: "//N GAMEOBJECT_TYPE_X" opens a type, "uint32 name; //k" names its Data k.
union = source[source.index("struct GameObjectTemplate\n"):]
union = union[:union.index("raw;") if "raw;" in union else len(union)]
current = None
labels = {}
for line in union.splitlines():
    header = re.match(r"\s*//(\d+) GAMEOBJECT_TYPE_", line)
    field = re.match(r"\s*uint32 (\w+);\s*//(\d+)", line)
    if header:
        current = int(header.group(1))
        labels[current] = {}
    elif field and current is not None:
        labels[current][int(field.group(2))] = field.group(1)
if len(labels) < 30:
    raise SystemExit(f"only {len(labels)} gameobject types parsed")
for type_id, names in sorted(labels.items()):
    body = ", ".join(f"[{k}] = {lua(v)}" for k, v in sorted(names.items()))
    lines.append(f"        [{type_id}] = {{ {body} }},")
lines += ["    },", "}", ""]

out = REPO / "Addons" / "EsteriaToolChest" / "Meta.lua"
out.write_text("\n".join(lines), encoding="utf-8", newline="\n")
print(out, len(lines), "lines;", ", ".join(f"{f}={len(values(p, k)) if p else 3}" for f, (p, k) in FIELDS.items()))

#include "DeformMath.h"
#include <cassert>
#include <cstdio>
#include <limits>
#include <vector>

static void UnitNormal(const Deform::Vertex& vertex) {
    float length = 0;
    for (float value : vertex.normal) { assert(std::isfinite(value)); length += value*value; }
    assert(std::fabs(length-1) < .001f);
    for (float value : vertex.position) assert(std::isfinite(value));
}
int main(int argc, char** argv) {
    unsigned tested = 0;
    for (const auto& profile : Deform::kProfiles) {
        assert(profile.support == 0x7fffff);
        for (int slider = 12; slider < 37; ++slider) {
            bool body = slider < 14;
            Deform::Vertex vertex{};
            unsigned bone = 0;
            for (; bone < profile.boneCount; ++bone) if (profile.boneFlags[bone]&(body ? 2 : 1)) break;
            assert(bone < profile.boneCount);
            vertex.bones[0] = static_cast<uint8_t>(bone); vertex.weights[0] = 255;
            vertex.normal[0] = 1;
            int region = body ? (slider-12)*2 : 4;
            std::memcpy(vertex.position, profile.zones[region].center, 12);
            // An offset from a region centre exercises scale as well as translation controls.
            vertex.position[0] += profile.zones[region].radius[0]*.15f;
            vertex.position[1] += profile.zones[region].radius[1]*.12f;
            vertex.position[2] += profile.zones[region].radius[2]*.12f;
            float values[37]{};
            Deform::Vertex out;
            assert(!Deform::Apply(out,vertex,profile,values,0));
            assert(std::memcmp(&out,&vertex,sizeof(out)) == 0);
            values[slider] = 1;
            Deform::Apply(out,vertex,profile,values,0); UnitNormal(out);
            if (slider == 12 && !profile.female) assert(std::memcmp(&out,&vertex,sizeof(out)) == 0);
            values[slider] = -1;
            if (slider < 14) assert(!Deform::Apply(out,vertex,profile,values,0));
            else { Deform::Apply(out,vertex,profile,values,0); UnitNormal(out); }
            values[slider] = std::numeric_limits<float>::quiet_NaN();
            assert(!Deform::Apply(out,vertex,profile,values,0));
            assert(std::memcmp(&out,&vertex,sizeof(out)) == 0);
            ++tested;
        }
        Deform::Vertex vertex{};
        vertex.normal[2] = 1;
        vertex.weights[0] = 255; // Root influences are not allowed to reshape a distant point.
        vertex.position[0] = vertex.position[1] = vertex.position[2] = 100;
        float values[37];
        for (float& value : values) value = 1;
        Deform::Vertex out;
        assert(!Deform::Apply(out,vertex,profile,values,0));
        assert(std::memcmp(&out,&vertex,sizeof(out)) == 0);
    }
    // Optional full raw meshes generated by test_deform_audit.py --mesh-fixtures.
    if (argc == 2) {
        for (unsigned p = 0; p < 20; ++p) {
            char filename[1024]{};
            std::snprintf(filename,sizeof(filename),"%s/%u.vertices",argv[1],p);
            FILE* stream = nullptr;
            assert(fopen_s(&stream,filename,"rb") == 0);
            uint32_t count = 0;
            assert(std::fread(&count,4,1,stream) == 1);
            std::vector<Deform::Vertex> vertices(count);
            assert(std::fread(vertices.data(),48,count,stream) == count);
            std::fclose(stream);
            const auto& profile = Deform::kProfiles[p];
            assert(Deform::Find(profile.path,vertices.data(),count) == &profile);
            vertices[0].uv[0] += .125f;
            assert(!Deform::Find(profile.path,vertices.data(),count));
            vertices[0].uv[0] -= .125f;
            for (int slider = 12; slider < 37; ++slider) {
                unsigned changed = 0;
                float values[37]{}; values[slider] = 1;
                for (uint32_t i = 0; i < count; ++i) {
                    Deform::Vertex out;
                    if (Deform::Apply(out,vertices[i],profile,values,i)) {
                        ++changed;
                        UnitNormal(out);
                    }
                    assert(std::memcmp(out.weights,vertices[i].weights,8) == 0);
                    assert(std::memcmp(out.uv,vertices[i].uv,16) == 0);
                    if (slider >= 14) {
                        values[slider] = -1;
                        if (Deform::Apply(out,vertices[i],profile,values,i)) UnitNormal(out);
                        values[slider] = 1;
                    }
                }
                if (Deform::HasSlider(profile,slider)) {
                    if (!changed) std::fprintf(stderr,"No effect: %s slot %d\n",profile.path,slider);
                    assert(changed);
                } else assert(!changed);
            }
            float values[37];
            for (float& value : values) value = 1;
            for (uint32_t i = 0; i < count; ++i) {
                Deform::Vertex out;
                Deform::Apply(out,vertices[i],profile,values,i);
                for (float coordinate : out.position) assert(std::isfinite(coordinate));
                for (float normal : out.normal) assert(std::isfinite(normal));
            }
        }
    }
    std::printf("Deformation math: %u profile/slider cases; full meshes %s\n",tested,argc == 2 ? "passed" : "not requested");
    return 0;
}

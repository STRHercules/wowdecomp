"""Import approved Fortnite 2H-axe defaults and ONLY the Wolf Pup fit from supplied fitter exports."""
import csv,json,math
from pathlib import Path

ROOT=Path(__file__).resolve().parents[2]
PICKAXES=Path('G:/3.3.5a - Dev/WTF/Esteria/PickaxeFits/PickaxeFits-20261114-092812.txt')
PETS=Path('G:/3.3.5a - Dev/WTF/Esteria/BackpackFits/BackpackFits-20261114-092930.txt')

def parse(pickaxes,pets):
    def rows(text):return csv.reader((line for line in text.splitlines() if line.strip() and not line.startswith('#')),delimiter=';')
    weapon={}
    for row in rows(pickaxes):
        if len(row)!=10 or int(row[0])!=3430001 or row[9] not in ('drawn','sheathed') or row[9] in weapon:
            raise ValueError('Expected one Rainbow Smash fit per weapon state')
        fit=list(map(float,row[2:9]))
        if not all(math.isfinite(v) for v in fit) or not .1<=fit[0]<=4 or any(abs(v)>3 for v in fit[1:4]) or any(abs(v)>180 for v in fit[4:]):raise ValueError('Invalid weapon fit')
        weapon[row[9]]=fit
    if set(weapon)!={'drawn','sheathed'}:raise ValueError('Both weapon states required')
    wolf=[]
    for row in rows(pets):
        if row[0]!='3400100':continue
        if len(row)!=6:raise ValueError('Malformed Wolf Pup profile')
        wolf.append(list(map(float,row[2:6])))
    if len(wolf)!=1 or not all(math.isfinite(v) for v in wolf[0]) or not .1<=wolf[0][0]<=4 or any(abs(v)>3 for v in wolf[0][1:]):raise ValueError('Exactly one valid Wolf Pup profile required')
    return {'fortnite_2h_axes':weapon,'pet_backpacks':wolf[0]}

def main():
    data=parse(PICKAXES.read_text(),PETS.read_text())
    out=Path(__file__).with_name('family-default-fits.json');out.write_text(json.dumps(data,indent=2)+'\n')
    target=Path(__file__).with_name('backpack-default-fits.txt');lines=target.read_text().splitlines();found=0
    for i,line in enumerate(lines):
        if line.startswith('3400100;'):
            lines[i]='3400100;retail/974343.m2;'+';'.join(f'{v:.6f}' for v in data['pet_backpacks']);found+=1
    if found!=1:raise ValueError('Wolf Pup default row missing or duplicated')
    target.write_text('\n'.join(lines)+'\n')
    values=lambda mode:','.join(f'{v:.6f}f' for v in data['fortnite_2h_axes'][mode])
    header='''#pragma once
#include <array>
namespace Retail {
// Approved Fortnite two-handed axe family defaults; generated by import_family_fits.py.
inline std::array<float,7> PickaxeDefaultFit(bool sheathed) {
    return sheathed ? std::array<float,7>{SHEATHED} : std::array<float,7>{DRAWN};
}
}
'''.replace('SHEATHED',values('sheathed')).replace('DRAWN',values('drawn'))
    (ROOT/'Engine/Source/Retail/PickaxeDefaults.h').write_text(header)
    print(json.dumps(data))

if __name__=='__main__':main()

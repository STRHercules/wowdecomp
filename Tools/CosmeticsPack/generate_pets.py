"""Build companion previews from effective client spells and live realm display mappings."""
import ctypes,json
from pathlib import Path
import stage

def generate():
    def readonly(self,path):
        handle=stage.mc.ed.cmp.H()
        if not self.dll.SFileOpenArchive(str(path),0,0x100,ctypes.byref(handle)):
            raise ctypes.WinError(ctypes.get_last_error())
        return handle
    stage.mc.ed.cmp.Storm.open_archive=readonly
    stage.mc.LAYOUT['SummonProperties']=(6,())
    client=stage.mc.Client(Path('G:/3.3.5a - Dev'),True)
    try:
        spells=client.table('Spell').rows;props=client.table('SummonProperties').rows
        displays=client.table('CreatureDisplayInfo').rows;models=client.table('CreatureModelData').rows
        icons=client.table('SpellIcon').rows
        creature_models={}
        for line in stage.db.mysql('SELECT CreatureID,CreatureDisplayID FROM creature_template_model ORDER BY CreatureID,Probability DESC,Idx','acore_world').splitlines():
            creature,display=map(int,line.split('\t'));creature_models.setdefault(creature,display)
        rows=[]
        for spell,(r,text) in spells.items():
            if r[71]!=28 or r[113] not in props or props[r[113]][0][4]!=5:continue
            name=text.get(136)
            if not name:continue
            row=dict(kind='pet',spell=spell,name=name,creature=r[110],icon=icons.get(r[133],([],{}))[1].get(1,'Interface\\Icons\\INV_Box_PetCarrier_01'))
            display=creature_models.get(r[110],0)
            if display in displays:
                modelid=displays[display][0][1]
                path=models.get(modelid,([],{}))[1].get(2)
                if path:row.update(model=path[:-4]+'.m2' if path.lower().endswith('.mdx') else path,creatureDisplay=display)
            rows.append(row)
        assert len(rows)>100 and any('Rabbit' in r['name'] for r in rows), 'Expected a populated companion catalog'
        target=stage.REPO/'Addons/EsteriaCosmetics/EsteriaPetsData.lua'
        target.write_text('-- Generated by Tools/CosmeticsPack/generate_pets.py.\nEsteriaCollectionsPets = {\n'+
            ''.join('    {'+','.join(k+'='+json.dumps(v) for k,v in row.items())+'},\n' for row in sorted(rows,key=lambda r:r['spell']))+'}\n')
        print('Generated',len(rows),'pets;',sum('model' in r for r in rows),'resolved models')
    finally:client.archives.close()

if __name__=='__main__':generate()

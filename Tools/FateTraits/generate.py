"""Turns Esteria_Fate_Trait_Catalog.json + effects.py into the files both repos build from, so they cannot drift:

  EsteriaWoW/src/server/shared/PerkTraitCatalog.h   the server's rules table and effect rows
  Tools/RetailAssets/glue/fate_traits.lua           names and texts for the creator and the in-game addon

  python generate.py            write both (--server points at the EsteriaWoW checkout)
  python generate.py --check    fail if either file is out of date (CI drift check)
  python generate.py --stamp    also record effects and status in the catalog JSON
"""
import argparse
import json
import sys
from pathlib import Path

from effects import EFFECTS, LOCKED

REPO = Path(__file__).resolve().parents[2]
CATALOG = REPO / "Esteria_Fate_Trait_Catalog.json"
LUA = REPO / "Tools" / "RetailAssets" / "glue" / "fate_traits.lua"
KINDS = {"neutral": "Neutral", "quirk": "Quirk", "merit": "Merit", "flaw": "Flaw"}
FLAG_LOCKS = {"Esteria.Fate.HousingTraits.Enable": "Needs housing integration",
              "Esteria.Fate.QuestCategoryTraits.Enable": "Needs quest categories",
              "Esteria.Fate.WeatherTraits.Enable": "Needs weather tracking"}


def need_of(text):
    text = text.lower()
    if "pet" in text:
        return "Pet"
    if "heal" in text:
        return "Healer"
    if "mana" in text or "spellcaster" in text:
        return "Mana"
    return "None"


def load():
    data = json.loads(CATALOG.read_text(encoding="utf-8"))
    traits = data["traits"]
    assert [t["id"] for t in traits] == list(range(163)), "ids must be 0..162 in order"
    assert len({t["name"] for t in traits}) == len(traits), "duplicate trait name"
    by_name = {t["name"]: t["id"] for t in traits}
    groups = {t["id"]: [] for t in traits}
    assert len(data["conflict_sets"]) <= 32
    for index, names in enumerate(data["conflict_sets"]):
        for name in names:
            groups[by_name[name]].append(index)
    for t in traits:
        t["groups"] = groups[t["id"]]
        t["need"] = need_of(t["eligibility"])
        t["points"] = t["cost"] or t["grant"]
        t["effects"] = EFFECTS.get(t["id"], [])
        t["live"] = t["id"] == 0 or bool(t["effects"])
        assert not t["effects"] or len(t["effects"]) >= (2 if t["kind"] == "quirk" else 1), t["name"]
        t["lock"] = "" if t["live"] else LOCKED.get(t["id"]) or FLAG_LOCKS.get(t["feature_flag"]) or "Coming later"
    assert set(EFFECTS) <= set(range(1, 163))
    return data, traits


def header(data, traits):
    rules = data["point_rules"]
    out = ["// Generated by wowdecomp Tools/FateTraits/generate.py from Esteria_Fate_Trait_Catalog.json. Do not edit.",
           "// Included by PerkTraitRules.h, inside namespace EsteriaTraits.", "",
           f"inline constexpr uint8_t BasePoints = {rules['base']}, MaxFlawPoints = {rules['max_flaw_points']}, "
           f"MaxMerits = {rules['max_merits']}, MaxFlaws = {rules['max_flaws']}, MaxQuirks = {rules['max_quirks']};", "",
           "// id, kind, points (a merit's cost, a flaw's grant), need, implemented, conflict groups (one bit each)",
           "inline constexpr Def Defs[] = {"]
    for t in traits:
        mask = sum(1 << g for g in t["groups"])
        out.append(f"    {{ {t['id']}, {KINDS[t['kind']]}, {t['points']}, Need{t['need']}, "
                   f"{'true' if t['live'] else 'false'}, 0x{mask:08X} }}, // {t['name']}")
    out += ["};", "", "inline constexpr Effect Effects[] = {"]
    for t in traits:
        for family, value in t["effects"]:
            out.append(f"    {{ {t['id']}, {family}, {value}f }},")
    out += ["};", ""]
    return "\n".join(out)


def lua_string(text):
    return '"' + text.replace("−", "-").replace("\\", "\\\\").replace('"', '\\"') + '"'


def lua(data, traits):
    rules = data["point_rules"]
    out = ["-- Generated by Tools/FateTraits/generate.py from Esteria_Fate_Trait_Catalog.json. Do not edit.",
           "-- Starting traits: texts and the advisory copy of the rules (the server's are PerkTraitRules.h).",
           "-- need: 1 mana, 2 combat pet, 3 healing spells. lock: why it cannot be picked yet.",
           "EsteriaFateTraits = {",
           f"    base = {rules['base']}, maxFlawPoints = {rules['max_flaw_points']}, maxMerits = {rules['max_merits']}, "
           f"maxFlaws = {rules['max_flaws']}, maxQuirks = {rules['max_quirks']},",
           "    list = {"]
    needs = {"None": 0, "Mana": 1, "Pet": 2, "Healer": 3}
    for t in traits[1:]:
        fields = [f"id = {t['id']}", f"kind = {lua_string(t['kind'])}", f"cat = {lua_string(t['category'])}",
                  f"name = {lua_string(t['name'])}", f"pts = {t['points']}"]
        if t["benefit"] != "None":
            fields.append(f"up = {lua_string(t['benefit'])}")
        if t["drawback"] != "None":
            fields.append(f"down = {lua_string(t['drawback'])}")
        if t["need"] != "None":
            fields.append(f"need = {needs[t['need']]}")
        if t["groups"]:
            fields.append("groups = { " + ", ".join(str(g + 1) for g in t["groups"]) + " }")
        if t["lock"]:
            fields.append(f"lock = {lua_string(t['lock'])}")
        out.append("        { " + ", ".join(fields) + " },")
    out += ["    },", "};", ""]
    return "\n".join(out)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--server", type=Path, default=REPO.parent / "EsteriaWoW")
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--stamp", action="store_true")
    args = parser.parse_args()
    data, traits = load()
    stale = []
    for path, text in ((args.server / "src" / "server" / "shared" / "PerkTraitCatalog.h", header(data, traits)),
                       (LUA, lua(data, traits))):
        if not path.exists() or path.read_text(encoding="utf-8") != text:
            stale.append(str(path))
            if not args.check:
                path.write_text(text, encoding="utf-8", newline="\n")
    if args.stamp:
        for t in traits:
            if t["id"]:
                t["effect_handlers"] = [list(e) for e in t["effects"]]
                t["implementation_status"] = "implemented" if t["live"] else "not_implemented"
            for key in ("groups", "need", "points", "effects", "live", "lock"):
                t.pop(key)
        CATALOG.write_text(json.dumps(data, indent=2, ensure_ascii=False) + "\n", encoding="utf-8", newline="\n")
    live = sum(1 for t in traits if t.get("live", True)) - 1
    print(f"{'stale' if args.check else 'wrote'}: {stale or 'nothing'}; {live if not args.stamp else len(EFFECTS)} traits live")
    sys.exit(1 if args.check and stale else 0)


if __name__ == "__main__":
    main()

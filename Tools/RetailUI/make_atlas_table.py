"""Write the retail UI atlas table the client's native SetAtlas reads (Interface\\Esteria\\RetailAtlas.txt in an MPQ).

    python -I make_atlas_table.py <UiTextureAtlas.csv> <UiTextureAtlasMember.csv> <UiTextureAtlasElement.csv> <out.txt>

The CSVs are wago.tools exports (https://wago.tools/db2/<table>/csv); neither a local install nor the pinned CDN
build decrypts these two tables. One line per atlas element, keyed by the element name retail code uses:

    name;fileDataId;width;height;left;right;top;bottom;flags

width/height are the element's 1x UI size, the coordinates are into the texture the client loads as
retail/<fileDataId>.blp, and flags are retail's CommittedFlags (4 tiles horizontally, 2 tiles vertically).
Classic and mainline both ship some elements; the newest 1x member wins, and its 2x member supplies the texture
when retail has one, since the client usually runs at a large UI scale.
"""
import csv
import re
import sys


def build(atlases_csv, members_csv, elements_csv):
    atlases = {r["ID"]: r for r in csv.DictReader(open(atlases_csv, encoding="utf-8"))}
    names = {r["ID"]: r["Name"] for r in csv.DictReader(open(elements_csv, encoding="utf-8"))}
    one, two = {}, {}
    for m in csv.DictReader(open(members_csv, encoding="utf-8")):
        a = atlases.get(m["UiTextureAtlasID"])
        name = names.get(m["UiTextureAtlasElementID"]) or m["CommittedName"]
        if not a or not name or int(a["AtlasWidth"]) <= 0 or int(a["AtlasHeight"]) <= 0:
            continue
        is2x = bool(re.search(r"[-_]2x$", m["CommittedName"], re.I))
        slot = two if is2x else one
        old = slot.get(name.lower())
        if not old or int(m["ID"]) > int(old[0]["ID"]):
            slot[name.lower()] = (m, a, name)
    rows = []
    for key, (m, a, name) in one.items():
        tex_m, tex_a, _ = two.get(key, (m, a, name))
        w, h = int(tex_a["AtlasWidth"]), int(tex_a["AtlasHeight"])
        rows.append((name, int(tex_a["FileDataID"]), int(m["Width"]), int(m["Height"]),
                     int(tex_m["CommittedLeft"]) / w, int(tex_m["CommittedRight"]) / w,
                     int(tex_m["CommittedTop"]) / h, int(tex_m["CommittedBottom"]) / h, int(m["CommittedFlags"])))
    for key, (m, a, name) in two.items():  # 2x-only elements: halve to the UI size
        if key not in one:
            w, h = int(a["AtlasWidth"]), int(a["AtlasHeight"])
            rows.append((name, int(a["FileDataID"]), int(m["Width"]) // 2, int(m["Height"]) // 2,
                         int(m["CommittedLeft"]) / w, int(m["CommittedRight"]) / w,
                         int(m["CommittedTop"]) / h, int(m["CommittedBottom"]) / h, int(m["CommittedFlags"])))
    return sorted(rows, key=lambda r: r[0].lower())


def main(atlases_csv, members_csv, elements_csv, out):
    rows = build(atlases_csv, members_csv, elements_csv)
    with open(out, "w", encoding="utf-8", newline="\n") as f:
        f.write("# Generated by wowdecomp Tools/RetailUI/make_atlas_table.py. Do not edit.\n")
        for r in rows:
            if ";" in r[0]:
                continue
            f.write(f"{r[0]};{r[1]};{r[2]};{r[3]};{r[4]:.6f};{r[5]:.6f};{r[6]:.6f};{r[7]:.6f};{r[8]}\n")
    print(f"{len(rows)} atlas elements -> {out}")


if __name__ == "__main__":
    if len(sys.argv) != 5:
        sys.exit(__doc__)
    main(*sys.argv[1:])

"""Write Enum, Constants and the C_ namespace list from retail's API documentation (Blizzard_APIDocumentationGenerated).

    python make_enums.py <apidocumentation-dir> <out Enum.lua>

The retail engine builds Enum.* and Constants.* itself; on 3.3.5a they are plain tables the retail UI reads. Values are
the shipped ones. Needs lupa (pip install lupa) to run the documentation files as Lua.
"""
import os
import sys

import lupa


def main(doc_dir, out):
    lua = lupa.LuaRuntime(unpack_returned_tuples=True)
    tables = lua.eval("{}")
    # Defaults in the docs may name Enum/Constants values; any lookup answers 0 while documenting.
    lua.execute("local any = setmetatable({}, { __index = function() return 0 end })\n"
                "Enum = setmetatable({}, { __index = function() return any end })\n"
                "Constants = setmetatable({}, { __index = function() return any end })")
    lua.globals().APIDocumentation = lua.eval("function(t) return { AddDocumentationTable = function(_, x) t[#t + 1] = x end } end")(tables)
    for name in sorted(os.listdir(doc_dir)):
        if name.endswith(".lua"):
            lua.execute(open(os.path.join(doc_dir, name), encoding="utf-8").read())

    enums, constants, namespaces = {}, {}, set()
    for doc in tables.values():
        if doc.Namespace:
            namespaces.add(doc.Namespace)
        for t in (doc.Tables or lua.eval("{}")).values():
            if t.Type == "Enumeration":
                enums[t.Name] = ([(f.Name, f.EnumValue) for f in t.Fields.values()], t.NumValues, t.MinValue, t.MaxValue)
            elif t.Type == "Constants":
                constants[t.Name] = [(v.Name, v.Value) for v in t.Values.values()]

    def lit(value):
        if isinstance(value, str):
            return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'
        if isinstance(value, bool):
            return "true" if value else "false"
        if value is None:
            return "nil"
        return repr(value) if isinstance(value, (int, float)) else "nil"

    with open(out, "w", encoding="utf-8", newline="\n") as f:
        f.write("-- Generated by wowdecomp Tools/RetailUI/make_enums.py from retail's API documentation. Do not edit.\n")
        f.write("Enum = Enum or {}\nConstants = Constants or {}\n")
        # Other addons often ship partial backports of these tables; fill in the missing fields rather than skip.
        f.write("local function merge(root, name, values)\n"
                "\tlocal t = rawget(root, name) or {}\n"
                "\tfor k, v in pairs(values) do if t[k] == nil then t[k] = v end end\n"
                "\troot[name] = t\n"
                "end\n")
        for name in sorted(enums):
            fields, num, lo, hi = enums[name]
            body = ", ".join(f"{k} = {lit(v)}" for k, v in fields)
            f.write(f'merge(Enum, "{name}", {{ {body} }})\n')
            f.write(f'merge(Enum, "{name}Meta", {{ NumValues = {lit(num)}, MinValue = {lit(lo)}, MaxValue = {lit(hi)} }})\n')
        for name in sorted(constants):
            body = ", ".join(f"{k} = {lit(v)}" for k, v in constants[name] if lit(v) != "nil")
            f.write(f'merge(Constants, "{name}", {{ {body} }})\n')
        f.write("EsteriaRetailUI.namespaces = { " + ", ".join(f'"{n}"' for n in sorted(namespaces)) + " }\n")
    print(f"{len(enums)} enums, {len(constants)} constant tables, {len(namespaces)} namespaces -> {out}")


if __name__ == "__main__":
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    main(*sys.argv[1:])

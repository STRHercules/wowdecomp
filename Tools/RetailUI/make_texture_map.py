"""Map the texture paths the extracted retail UI names to their FileDataIDs (RetailTextures.txt).

    python -I make_texture_map.py <community-listfile.csv> <extracted-root> <out.txt>

The client loads a mapped path from the Retail source (retail/<id>.blp) only when the path is missing from its own
archives, so stock textures with the same name are never replaced. One "path;fdid" line per texture, path lowercase
with forward slashes and no extension.
"""
import os
import re
import sys

PATH = re.compile(r"""(?:file\s*=\s*"|["'])(interface[\\/][^"'<>|]+?)(?:\.blp|\.tga)?["']""", re.I)


def norm(path):
    return re.sub(r"\.(blp|tga)$", "", path.replace("\\\\", "/").replace("\\", "/").lower())


def main(listfile, root, out):
    wanted = set()
    for base, _, files in os.walk(root):
        for name in files:
            if name.endswith((".lua", ".xml")):
                text = open(os.path.join(base, name), encoding="utf-8", errors="replace").read()
                wanted.update(norm(p) for p in PATH.findall(text))
    found = {}
    for line in open(listfile, encoding="utf-8", errors="replace"):
        fid, _, path = line.rstrip().partition(";")
        if path.endswith(".blp"):
            key = path[:-4]
            if key in wanted:
                found[key] = fid
    with open(out, "w", encoding="utf-8", newline="\n") as f:
        f.write("# Generated by wowdecomp Tools/RetailUI/make_texture_map.py. Do not edit.\n")
        for key in sorted(found):
            f.write(f"{key};{found[key]}\n")
    print(f"{len(found)} of {len(wanted)} referenced texture paths mapped -> {out}")


if __name__ == "__main__":
    if len(sys.argv) != 4:
        sys.exit(__doc__)
    main(*sys.argv[1:])

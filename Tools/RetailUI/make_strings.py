"""Write the retail global strings the extracted UI uses (enUS), for names the stock client does not define.

    python -I make_strings.py <GlobalStrings.csv> <extracted-root> <out GlobalStrings.lua>

GlobalStrings.csv is the wago.tools export (https://wago.tools/db2/GlobalStrings/csv). Only names that appear in the
extracted retail Lua/XML are written; at load each is set only if the stock UI has no string of that name, so stock
text never changes.
"""
import csv
import os
import re
import sys


def lua_string(text):
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"').replace("\r", "").replace("\n", "\\n") + '"'


def main(strings_csv, root, out):
    used = set()
    for base, _, files in os.walk(root):
        for name in files:
            if name.endswith((".lua", ".xml")):
                used.update(re.findall(r"\b[A-Z][A-Z0-9_]{2,}\b", open(os.path.join(base, name), encoding="utf-8", errors="replace").read()))
    rows = {}
    for row in csv.DictReader(open(strings_csv, encoding="utf-8")):
        tag = row["BaseTag"]
        if tag in used and tag not in rows:
            rows[tag] = row["TagText_lang"]
    with open(out, "w", encoding="utf-8", newline="\n") as f:
        f.write("-- Generated by wowdecomp Tools/RetailUI/make_strings.py from retail GlobalStrings (enUS). Do not edit.\n")
        f.write("local strings = {\n")
        for tag in sorted(rows):
            f.write(f"\t{tag} = {lua_string(rows[tag])},\n")
        f.write("}\nfor name, text in pairs(strings) do if _G[name] == nil then _G[name] = text end end\n")
    print(f"{len(rows)} strings -> {out}")


if __name__ == "__main__":
    if len(sys.argv) != 4:
        sys.exit(__doc__)
    main(*sys.argv[1:])

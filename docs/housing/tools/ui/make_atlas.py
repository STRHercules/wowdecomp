"""Write Addons/EsteriaHousing/Atlas.lua: the retail housing UI atlas elements the addon draws with.

    python -I make_atlas.py <UiTextureAtlas.csv> <UiTextureAtlasMember.csv> <community-listfile.csv> <Atlas.lua>

The CSVs are wago.tools exports (https://wago.tools/db2/<table>/csv); the pinned CDN build would not decrypt these
tables. Each element becomes { fileDataId, width, height, left, right, top, bottom }: the texture the client loads as
retail/<fileDataId>.blp, the element's size in UI units (the 1x size), and its texture coordinates. Where retail has a
2x atlas the 2x texture is used, since the client usually runs at a large UI scale.
"""
import csv
import re
import sys

WANTED = re.compile(r"^(category-icons_[a-z-]+_(active|inactive|pressed)|house-chest-.*|decor-controls-.*|controls-frame"
                    r"|decor-ability.*|decor-abilitybar-.*|house-decor-budget-icon|house-room-limit-icon|housing-floor-.*"
                    r"|housing-layout-room-.*|layout_.*_icon|housing-basic-.*|housing-wood-frame.*|catalog-.*"
                    r"|housing-hotkey-icon-.*|housing-woodsign|housing-decorative-foliage-.*)$")


def main(atlases_csv, members_csv, listfile, out):
    paths = {}
    for line in open(listfile, encoding="utf-8", errors="replace"):
        i, _, p = line.rstrip().partition(";")
        if p.startswith("interface/"):
            paths[i] = p
    atlases = {r["ID"]: r for r in csv.DictReader(open(atlases_csv, encoding="utf-8"))
               if r["FileDataID"] in paths and paths[r["FileDataID"]].startswith("interface/housing/")}
    best = {}
    for m in csv.DictReader(open(members_csv, encoding="utf-8")):
        a = atlases.get(m["UiTextureAtlasID"])
        if not a:
            continue
        name = re.sub(r"[-_]2x$", "", m["CommittedName"])
        if not WANTED.match(name):
            continue
        hi = "2x" in paths[a["FileDataID"]].rsplit("/", 1)[-1]
        w, h = int(a["AtlasWidth"]), int(a["AtlasHeight"])
        entry = {"fdid": int(a["FileDataID"]), "hi": hi,
                 "size": (int(m["Width"]) // (2 if hi else 1), int(m["Height"]) // (2 if hi else 1)),
                 "coords": (int(m["CommittedLeft"]) / w, int(m["CommittedRight"]) / w,
                            int(m["CommittedTop"]) / h, int(m["CommittedBottom"]) / h)}
        old = best.get(name)
        if not old or (hi and not old["hi"]):
            if old and not old["hi"]:
                entry["size"] = old["size"]  # the 1x member's size is the element's UI size
            best[name] = entry
        elif old["hi"] and not hi:
            old["size"] = entry["size"]
    with open(out, "w", encoding="utf-8", newline="\n") as f:
        f.write("-- Generated by wowdecomp docs/housing/tools/ui/make_atlas.py from retail UiTextureAtlas(Member). Do not edit.\n")
        f.write("-- name = { fileDataId, width, height, left, right, top, bottom }; textures load as retail/<fileDataId>.blp\n")
        f.write("EsteriaHousingUI = EsteriaHousingUI or {}\nEsteriaHousingUI.ATLAS = {\n")
        for name in sorted(best):
            e = best[name]
            f.write(f'  ["{name}"] = {{ {e["fdid"]}, {e["size"][0]}, {e["size"][1]}, '
                    + ", ".join(f"{c:.6f}" for c in e["coords"]) + " },\n")
        f.write("}\n")
    print(f"{len(best)} elements on {len({e['fdid'] for e in best.values()})} textures -> {out}")


if __name__ == "__main__":
    main(*sys.argv[1:5])
